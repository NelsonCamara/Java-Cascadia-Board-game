package cascadia.items;

/**
 * Enum representing the different types of habitats in the Cascadia game.
 * Each habitat type is associated with specific fauna and terrain characteristics.
 */
public enum TileType {

    /** Represents a mountain habitat. */
    MONTAGNE,

    /** Represents a forest habitat. */
    FORET,

    /** Represents a prairie habitat. */
    PRAIRIE,

    /** Represents a marsh habitat. */
    MARAIS,

    /** Represents a river habitat. */
    RIVIERE;
}