package cascadia.items;

/**
 * Enum representing the different types of fauna tokens in the Cascadia game.
 * Each fauna type corresponds to specific scoring rules and habitat preferences.
 */
public enum FaunaTokenType {

    /** Represents a bear fauna token. */
    OURS,

    /** Represents an elk fauna token. */
    WAPITI,

    /** Represents a salmon fauna token. */
    SAUMON,

    /** Represents a hawk fauna token. */
    BUSE,

    /** Represents a fox fauna token. */
    RENARD;
}